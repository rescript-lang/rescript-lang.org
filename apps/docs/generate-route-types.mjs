import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadRoutes } from "./route-config.mjs";

export const outputPath = fileURLToPath(
  new URL("../../packages/shared/src/Path.res", import.meta.url),
);

export function concretePaths(routes) {
  const paths = new Set();
  function visit(routes, parent = "") {
    for (const route of routes) {
      const path = route.path?.startsWith("/")
        ? route.path
        : `${parent}/${route.path ?? ""}`;
      const pathname = `/${path.split("/").filter(Boolean).join("/")}`;
      // Layouts have no URL of their own. Route patterns aren't link destinations.
      if (
        (route.index || route.path !== undefined) &&
        !/[:*?]/.test(pathname)
      ) {
        paths.add(pathname);
      }
      if (route.children) visit(route.children, pathname);
    }
  }
  visit(routes);
  return [...paths].sort();
}

export function renderPathType(routes) {
  const paths = concretePaths(routes);
  if (paths.length === 0) throw new Error("No concrete routes found.");
  return `// Generated by apps/docs/generate-route-types.mjs. Do not edit.
// Run yarn build:routes after changing routes, MDX pages, or API data.
type t = [
${paths.map((path) => `  | #${JSON.stringify(path)}`).join("\n")}
]
`;
}

export function generateRouteTypes({
  routes = loadRoutes().routes,
  destination = outputPath,
  check = false,
} = {}) {
  const source = renderPathType(routes);
  let current;
  try {
    current = readFileSync(destination, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (current === source) return true;
  if (check) return false;
  writeFileSync(destination, source);
  return true;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check")) {
    throw new Error("Usage: node generate-route-types.mjs [--check]");
  }
  if (!generateRouteTypes({ check: args.includes("--check") })) {
    console.error(
      "Route types are stale. Run yarn build:routes and commit packages/shared/src/Path.res.",
    );
    process.exitCode = 1;
  }
}
